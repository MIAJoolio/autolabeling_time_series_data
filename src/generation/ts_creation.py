class TS_block:
    """
    Базовый блок временного ряда, состоящий из 4 компонентов:
        - Тренд
        - Сезонность
        - Структурные сдвиги
        - Шум
    """

    def __init__(self, trend: TS_generator = None, seasonality: TS_generator = None, shifts: TS_generator = None, noise: Noise_generator = None, length:int=None): 
        
        for item in [trend, seasonality, shifts]:
            if item is not None:
                length = item.config['length']
                break
        if noise is not None and length is None:
            length = noise.data.shape[0]
        
        self.trend = trend.generate()[0] if trend is not None else np.zeros(length)
        self.seasonality = seasonality.generate()[0] if seasonality is not None else np.zeros(length)
        self.shifts = shifts.generate()[0] if shifts is not None else np.zeros(length)
        self.noise = noise.generate()[0] if noise is not None else np.zeros(length)

    
class TS_merger:
    """
    Управляет несколькими TS_block и собирает общий конфиг в формате YAML
    """

    def __init__(self):
        self.blocks: List[TS_block] = []

    def add_block(self, block: TS_block):
        self.blocks.append(block)

    def remove_block(self, index: int):
        if 0 <= index < len(self.blocks):
            self.blocks.pop(index)
        else:
            raise IndexError("Block index out of range")

    def generate(self) -> np.ndarray:
        if not self.blocks:
            return np.array([])

        full_series = None
        
        for block in self.blocks:
            
            new_series = block.trend + block.seasonality + block.shifts + block.noise
            if full_series is None:
                full_series = new_series[1:]
            else:
                start_point = block.trend[0] + block.seasonality[0] + block.shifts[0] + block.noise[0]
                end_point = full_series[-1]
                new_series = -start_point + end_point + new_series
                full_series = np.concatenate([full_series, new_series[1:]])
    
        return full_series

