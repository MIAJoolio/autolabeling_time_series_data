class TS_generator:
    """
    
    """
    def __init__(self, gen_func:Callable, config:Union[dict, str]=None):
        
        self.gen_func = gen_func
        if isinstance(config, dict):
            self.config = config
        elif isinstance(config, str):
            self.config = load_config_file(config) 
        else:
            self.config = {}  
    
    def generate_params(self, round_val: int = 3, all_values: bool = False, random_state: Optional[int] = None) -> Dict[str, Union[float, np.ndarray]]:
        """
        Generate parameters from function signature or configuration file. By default suggested that you shouldn't create configuration file and it's generated by function-generator itself. 
        Each parameters has upper,lower boundaries and number of steps which imititates difference
        """
        if random_state is not None:
            np.random.seed(random_state)
        elif self.config.get('random_state', None) is not None:
            np.random.seed(self.config.get('random_state'))
        
        # get signatures
        sig = inspect.signature(self.gen_func)
        params = {}

        # iterate through them and generate basic values
        for name, param in sig.parameters.items():
            if name == "length":
                self.config['length'] = self.config.get(name, param.default)
            else:        
                d = self.config.get(f"{name}_d", -1.0 if param.default == inspect.Parameter.empty else param.default)
                self.config[f"{name}_d"] = d
                u = self.config.get(f"{name}_u", 1.0 if d >= 0 else abs(d))
                self.config[f"{name}_u"] = u
                q = self.config.get(f"{name}_q", 10)
                self.config[f"{name}_q"] = q
                
                values = np.linspace(d, u, q).round(round_val)
                value = values if all_values else np.random.choice(values)
                params[name] = value

        if random_state is not None:
            self.config['random_state'] = random_state
    
        params['length'] = self.config['length']
        return params
    
    def generate(self, **kwargs) -> np.ndarray:
        """
        
        """
        if kwargs.get('all_values'):
            params_grid = self.generate_params(**kwargs)
            params = generate_combinations(params_grid)
            return [self.gen_func(**param) for param in params], params
            
        params = self.generate_params(**kwargs)
        return self.gen_func(**params), params 

    def save_config(self, config_path:str='configs/config_file.yaml'):
        split_name = config_path.split('.')
        name = '_'.join([split_name[0], str(self.config['length'])])
        fmt = split_name[-1]
        full_name = f"{name}.{fmt}"
        save_config_file(self.config, full_name)
        return full_name

    
